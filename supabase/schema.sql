-- Market Sentinel: database schema + Row Level Security
-- Safe to run more than once (idempotent).
--
-- Data model
--   watchlist      private  : one row per (user, ticker); a user only ever sees their own rows
--   price_history  shared   : daily OHLCV per ticker, one row per trading day
--   market_log     shared   : robot snapshots (price + headline + FinBERT sentiment)
--
-- Access
--   anon (not logged in) : nothing
--   authenticated        : own watchlist; read/add shared market data
--   service_role (robot) : bypasses RLS (GitHub Actions nightly scan)

set timezone = 'UTC';

-- 1. TABLES --------------------------------------------------------------
create table if not exists public.watchlist (
    id         bigint generated by default as identity primary key,
    user_id    uuid not null references auth.users (id) on delete cascade,
    ticker     text not null,
    created_at timestamptz not null default now()
);

create table if not exists public.price_history (
    id        bigint generated by default as identity primary key,
    ticker    text not null,
    timestamp timestamptz not null,
    open      double precision,
    high      double precision,
    low       double precision,
    close     double precision,
    volume    bigint
);

create table if not exists public.market_log (
    id         bigint generated by default as identity primary key,
    timestamp  timestamp not null default now(),
    ticker     text not null,
    price      double precision,
    headline   text,
    sentiment  text,
    confidence double precision
);

-- 2. CLEAN UP price_history ----------------------------------------------
-- Older rows were stored at the exchange's local midnight (05:00 UTC for New York,
-- 18:30 UTC of the previous day for India). Normalise every row to 00:00 UTC of
-- its trading day, keeping only the newest copy when a day appears twice.
delete from public.price_history p
using (
    select id,
           row_number() over (
               partition by ticker, date_trunc('day', timestamp + interval '12 hours')
               order by id desc) as rn
    from public.price_history
) d
where p.id = d.id and d.rn > 1;

update public.price_history
set timestamp = date_trunc('day', timestamp + interval '12 hours')
where timestamp <> date_trunc('day', timestamp + interval '12 hours');

do $$ begin
    if not exists (select 1 from pg_constraint where conname = 'price_history_ticker_timestamp_key') then
        alter table public.price_history
            add constraint price_history_ticker_timestamp_key unique (ticker, timestamp);
    end if;
end $$;

-- 3. CLEAN UP watchlist ---------------------------------------------------
delete from public.watchlist w
using (
    select id, row_number() over (partition by user_id, ticker order by id) as rn
    from public.watchlist
) d
where w.id = d.id and d.rn > 1;

do $$ begin
    if not exists (select 1 from pg_constraint where conname = 'watchlist_user_ticker_key') then
        alter table public.watchlist
            add constraint watchlist_user_ticker_key unique (user_id, ticker);
    end if;
end $$;

create index if not exists market_log_ticker_timestamp_idx on public.market_log (ticker, timestamp desc);

-- 4. ROW LEVEL SECURITY ---------------------------------------------------
alter table public.watchlist     enable row level security;
alter table public.price_history enable row level security;
alter table public.market_log    enable row level security;

-- Drop whatever policies existed before so the rules below are the only ones
do $$
declare p record;
begin
    for p in select policyname, tablename from pg_policies
             where schemaname = 'public' and tablename in ('watchlist', 'price_history', 'market_log')
    loop
        execute format('drop policy %I on public.%I', p.policyname, p.tablename);
    end loop;
end $$;

-- watchlist: private to its owner
create policy "watchlist_select_own" on public.watchlist
    for select to authenticated using ((select auth.uid())::text = user_id::text);
create policy "watchlist_insert_own" on public.watchlist
    for insert to authenticated with check ((select auth.uid())::text = user_id::text);
create policy "watchlist_delete_own" on public.watchlist
    for delete to authenticated using ((select auth.uid())::text = user_id::text);

-- price_history: shared market data, logged-in users can read and add/refresh rows
create policy "price_history_read" on public.price_history
    for select to authenticated using (true);
create policy "price_history_insert" on public.price_history
    for insert to authenticated with check (true);
create policy "price_history_update" on public.price_history
    for update to authenticated using (true) with check (true);

-- market_log: shared, logged-in users can read and seed a row for a new ticker
create policy "market_log_read" on public.market_log
    for select to authenticated using (true);
create policy "market_log_insert" on public.market_log
    for insert to authenticated with check (true);

-- Remove table-level grants from anon so nothing leaks even if RLS is ever disabled
revoke all on public.watchlist, public.price_history, public.market_log from anon;
